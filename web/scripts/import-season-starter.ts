// `npm run import:starter`: the Spooky English Quiz (SPOOKY_STARTER §4–§7, package S2).
//
// Reads the private seed Prototyp/marktplatz/sources/season-starter/quiz.private.json, validates it
// and writes it as the generated seed block of supabase/migrations/0051_season_starter.sql. The
// solutions and hints reach the database only; nothing of the seed goes to web/public or the bundle.
// The four Edge-TTS clips are copied to web/public/assets/listening under the shared listeningPath.
//
//   node scripts/import-season-starter.ts           check only (also part of npm test)
//   node scripts/import-season-starter.ts --write   rewrite the seed block and copy the clips
import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { LISTENING_RATE, LISTENING_VOICE, listeningPath } from '../src/quests/listening.ts';

const ROOT = fileURLToPath(new URL('../../', import.meta.url));
export const SEED_FILE = join(ROOT, 'Prototyp/marktplatz/sources/season-starter/quiz.private.json');
export const CLIP_SOURCE = join(ROOT, 'Prototyp/marktplatz');
export const MIGRATION = join(ROOT, 'supabase/migrations/0051_season_starter.sql');
const LOCK = join(ROOT, 'supabase/migrations.lock');
export const BEGIN = '-- BEGIN season-starter seed (generated by web/scripts/import-season-starter.ts)';
export const END = '-- END season-starter seed';

export interface StarterQuestion {
  id: string;
  kind: string;
  type: 'choice' | 'listening';
  mode?: 'choice';
  prompt: string;
  speak?: string;
  options: string[];
  solution: string;
  hint: string;
}
export interface StarterSeed {
  seasonId: string;
  xpPerSolvedQuestion: number;
  completionBonusXp: number;
  totalXp: number;
  voice: string;
  rate: string;
  questions: StarterQuestion[];
}

const ID = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

/** Throws with every problem at once; the rules of §4 and §7 (10 + 50 = 150 XP, ten questions). */
export function validateStarterSeed(raw: unknown): StarterSeed {
  const seed = raw as StarterSeed;
  const problems: string[] = [];
  if (!seed || typeof seed !== 'object') throw new Error('seed is not an object');
  if (typeof seed.seasonId !== 'string' || !seed.seasonId) problems.push('seasonId missing');
  if (seed.xpPerSolvedQuestion !== 10) problems.push('xpPerSolvedQuestion must be 10');
  if (seed.completionBonusXp !== 50) problems.push('completionBonusXp must be 50');
  if (seed.totalXp !== 150) problems.push('totalXp must be 150');
  if (seed.voice !== LISTENING_VOICE || seed.rate !== LISTENING_RATE)
    problems.push(`voice/rate must be ${LISTENING_VOICE} ${LISTENING_RATE}`);
  const questions = Array.isArray(seed.questions) ? seed.questions : [];
  if (questions.length !== 10) problems.push(`expected 10 questions, got ${questions.length}`);
  const ids = new Set<string>();
  for (const q of questions) {
    const where = `question ${q?.id ?? '?'}`;
    if (typeof q?.id !== 'string' || !ID.test(q.id)) problems.push(`${where}: invalid id`);
    if (ids.has(q.id)) problems.push(`${where}: duplicate id`);
    ids.add(q.id);
    if (q.type !== 'choice' && q.type !== 'listening')
      problems.push(`${where}: type must be choice or listening`);
    if (q.type === 'listening' && (q.mode !== 'choice' || typeof q.speak !== 'string' || !q.speak.trim()))
      problems.push(`${where}: listening needs mode choice and a spoken text`);
    if (q.type === 'choice' && q.speak !== undefined) problems.push(`${where}: only listening speaks`);
    for (const field of ['kind', 'prompt', 'solution', 'hint'] as const)
      if (typeof q?.[field] !== 'string' || !q[field].trim()) problems.push(`${where}: ${field} missing`);
    if (!Array.isArray(q?.options) || q.options.length < 3 || q.options.length > 4)
      problems.push(`${where}: three or four options`);
    else {
      if (new Set(q.options).size !== q.options.length) problems.push(`${where}: duplicate options`);
      if (q.options.filter((o) => o === q.solution).length !== 1)
        problems.push(`${where}: the solution must be exactly one of the options`);
    }
  }
  if (problems.length) throw new Error(`season starter seed is invalid:\n${problems.join('\n')}`);
  return seed;
}

function stable(value: unknown): string {
  if (Array.isArray(value)) return `[${value.map(stable).join(',')}]`;
  if (value && typeof value === 'object')
    return `{${Object.keys(value as Record<string, unknown>)
      .sort()
      .map((key) => `${JSON.stringify(key)}:${stable((value as Record<string, unknown>)[key])}`)
      .join(',')}}`;
  return JSON.stringify(value);
}

export function contentVersion(seed: StarterSeed): string {
  return createHash('sha256').update(stable(seed.questions)).digest('hex').slice(0, 16);
}

const lit = (text: string): string => `'${text.replace(/'/g, "''")}'`;

/** The generated insert block; deterministic, so a second run changes nothing. */
export function seedSql(seed: StarterSeed): string {
  const version = contentVersion(seed);
  const rows = seed.questions.map((q, index) => {
    const data: Record<string, unknown> = { options: q.options };
    if (q.type === 'listening') {
      data.mode = q.mode;
      data.speak = q.speak;
    }
    return `  (${lit(seed.seasonId)}, ${lit(q.id)}, ${index + 1}, ${lit(q.kind)}, ${lit(q.type)},
   ${lit(q.prompt)},
   ${lit(JSON.stringify(data))}::jsonb,
   ${lit(JSON.stringify(q.solution))}::jsonb,
   ${lit(q.hint)}, ${lit(version)})`;
  });
  return `${BEGIN}
insert into public.season_starter_questions
  (season_id, id, position, kind, type, prompt, data, solution, hint, content_version)
values
${rows.join(',\n')};
${END}`;
}

export function replaceSeedBlock(migration: string, block: string): string {
  const start = migration.indexOf(BEGIN);
  const end = migration.indexOf(END);
  if (start < 0 || end < start) throw new Error('seed markers missing in 0051_season_starter.sql');
  return migration.slice(0, start) + block + migration.slice(end + END.length);
}

export function clipPlan(seed: StarterSeed): Array<{ id: string; text: string; path: string }> {
  return seed.questions
    .filter((q) => q.type === 'listening')
    .map((q) => ({ id: q.id, text: q.speak!, path: listeningPath(q.speak!, seed.voice, seed.rate) }));
}

function main(): void {
  const write = process.argv.includes('--write');
  if (!existsSync(SEED_FILE)) {
    console.log('season starter: private seed not present, nothing to check');
    return;
  }
  const seed = validateStarterSeed(JSON.parse(readFileSync(SEED_FILE, 'utf8')));
  const migration = readFileSync(MIGRATION, 'utf8');
  const next = replaceSeedBlock(migration, seedSql(seed));
  const problems: string[] = [];
  if (next !== migration) {
    const lock = existsSync(LOCK) ? (JSON.parse(readFileSync(LOCK, 'utf8')) as Record<string, string>) : {};
    if (lock['0051_season_starter.sql'])
      problems.push('0051 is already live: add new questions in a new migration instead');
    else if (write) writeFileSync(MIGRATION, next);
    else problems.push('seed block in 0051_season_starter.sql is out of date (run with --write)');
  }
  for (const clip of clipPlan(seed)) {
    const target = join(ROOT, 'web/public', clip.path);
    const source = join(CLIP_SOURCE, clip.path);
    if (write && existsSync(source) && !existsSync(target)) copyFileSync(source, target);
    if (!existsSync(target) || statSync(target).size === 0)
      problems.push(`${clip.path} (${clip.text}) missing`);
  }
  if (problems.length) {
    console.error(problems.join('\n'));
    process.exit(1);
  }
  console.log(`season starter: ${seed.questions.length} questions, version ${contentVersion(seed)}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
